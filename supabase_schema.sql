-- Cricketle PostgreSQL Schema for Supabase (100% Free Tier)
-- How to apply: In your Supabase Dashboard, go to "SQL Editor", click "New Query", paste this file and click "Run".

-- 1. Settings Table
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- 2. Users Table
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  pass_hash TEXT,
  display_name TEXT,
  email TEXT,
  google_id TEXT UNIQUE,
  phone TEXT UNIQUE,
  avatar TEXT DEFAULT 'batter',
  bio TEXT DEFAULT '',
  fav_team TEXT DEFAULT '',
  fav_player TEXT DEFAULT '',
  is_admin BOOLEAN DEFAULT false,
  created_at BIGINT NOT NULL
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS is_admin BOOLEAN DEFAULT false;

CREATE INDEX IF NOT EXISTS idx_users_username ON users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_phone ON users (phone) WHERE phone IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_users_google ON users (google_id) WHERE google_id IS NOT NULL;

-- 3. Sessions Table
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions (expires_at);

-- 4. Puzzles Table
CREATE TABLE IF NOT EXISTS puzzles (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  mode TEXT NOT NULL,
  idx INTEGER NOT NULL,
  status TEXT NOT NULL,
  guesses JSONB NOT NULL DEFAULT '[]'::jsonb,
  hints INTEGER NOT NULL DEFAULT 0,
  started_at BIGINT,
  finished_at BIGINT,
  points INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, day, mode, idx)
);

CREATE INDEX IF NOT EXISTS idx_puzzles_user_day ON puzzles (user_id, day);
CREATE INDEX IF NOT EXISTS idx_puzzles_day_status ON puzzles (day, status);

-- 5. Leaderboard Functions (RPC)
CREATE OR REPLACE FUNCTION get_leaderboard_today(p_day TEXT, p_limit INTEGER DEFAULT 50)
RETURNS TABLE (
  user_id BIGINT,
  username TEXT,
  display_name TEXT,
  avatar TEXT,
  points BIGINT,
  solved BIGINT,
  guesses BIGINT,
  ms BIGINT,
  rank BIGINT,
  total BIGINT
) LANGUAGE sql STABLE AS $$
WITH agg AS (
  SELECT p.user_id, u.username, u.display_name, u.avatar,
         SUM(p.points) AS points,
         SUM(CASE WHEN p.status = 'solved' THEN 1 ELSE 0 END) AS solved,
         SUM(jsonb_array_length(p.guesses)) AS guesses,
         SUM(COALESCE(p.finished_at - p.started_at, 0)) AS ms
  FROM puzzles p JOIN users u ON u.id = p.user_id
  WHERE p.day = p_day AND p.status IN ('solved', 'gaveUp')
  GROUP BY p.user_id, u.username, u.display_name, u.avatar
),
ranked AS (
  SELECT agg.user_id, agg.username, agg.display_name, agg.avatar,
         agg.points, agg.solved, agg.guesses, agg.ms,
         RANK() OVER (ORDER BY points DESC, ms ASC, username ASC) AS rank,
         COUNT(*) OVER () AS total
  FROM agg
)
SELECT * FROM ranked ORDER BY rank, username LIMIT p_limit;
$$;

